import { test, expect } from '@playwright/test'
import fs from 'node:fs'

test('real console controls verified GOST through systemd without restarting its API', async ({
  page,
}) => {
  test.skip(
    !process.env.GOST_WEB_URL || !process.env.GOST_WEB_TOKEN_FILE,
    'requires the guarded systemd browser fixture',
  )
  test.setTimeout(180000)
  const token = fs.readFileSync(process.env.GOST_WEB_TOKEN_FILE!, 'utf8').trim()
  const headers = { Authorization: `Bearer ${token}` }
  const fixture = await (await page.request.get('/_fixture/info', { headers })).json()
  await page.goto('/')
  await page.getByLabel('管理员密码', { exact: true }).fill('invalid-token')
  await page.getByRole('button', { name: '登录控制台' }).click()
  await expect(page.getByText('invalid_credentials')).toBeVisible()
  await page.getByLabel('管理员密码', { exact: true }).fill(token)
  await page.getByRole('button', { name: '登录控制台' }).click()
  await page.getByRole('link', { name: '代理池与节点' }).click()
  await expect(page.getByRole('button', { name: '管理代理池' })).toBeVisible()
  await expect(page.locator('.node-table .el-table__body tr')).toHaveCount(2)
  console.log('PASS browser: authenticated real console')
  await page.screenshot({ animations: 'disabled', path: '../test-results/console-desktop.png' })
  console.log('PASS browser: desktop screenshot')
  await page.getByRole('combobox', { name: '当前出口', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'office', exact: true }).click()
  await expect(page.getByText('出口已切换，已有连接继续使用原路径')).toBeVisible()
  expect((await page.request.get('/_fixture/check', { headers })).ok()).toBe(true)
  console.log('PASS browser: hot profile switch preserves the existing stream and frontend PID')
  await page.getByRole('button', { name: '管理代理池' }).click()
  await page.getByRole('button', { name: '新建 profile' }).click()
  await page.getByLabel('profile 名称', { exact: true }).fill('web-pool')
  await page.getByLabel('探测目标地址', { exact: true }).fill(fixture.echo)
  await page.getByRole('button', { name: '保存到草稿' }).click()
  await expect(page.getByRole('dialog', { name: '新建 profile', exact: true })).not.toBeVisible()
  await page
    .getByRole('dialog', { name: '管理代理池与直连', exact: true })
    .getByRole('button', { name: '关闭此对话框' })
    .click()
  await page.getByRole('button', { name: '添加节点' }).click()
  await page.getByRole('combobox', { name: '节点所属池', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'web-pool', exact: true }).click()
  await page.getByLabel('节点 ID', { exact: true }).fill('browser-http')
  await page.getByRole('combobox', { name: '代理类型', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'HTTP CONNECT', exact: true }).click()
  await page.getByLabel('上游地址', { exact: true }).fill(fixture.upstream)
  await page.getByRole('switch', { name: '上游认证', exact: true }).locator('..').click()
  await page.getByLabel('上游用户名', { exact: true }).fill('fixture-upstream')
  await page.getByLabel('上游密码', { exact: true }).fill('fixture-upstream-password')
  await page.getByRole('button', { name: '保存到草稿' }).click()
  await page.getByRole('button', { name: '预览变更' }).click()
  await expect(page.getByTestId('config-preview')).not.toContainText('fixture-upstream-password')
  await page
    .getByRole('dialog', { name: '预览变更' })
    .getByRole('button', { name: '关闭此对话框' })
    .click()
  await page.getByRole('button', { name: '校验并应用' }).click()
  await expect(page.getByText('配置已应用', { exact: true })).toBeVisible()
  expect((await page.request.get('/_fixture/check', { headers })).ok()).toBe(true)
  await page.getByRole('combobox', { name: '当前出口', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'web-pool', exact: true }).click()
  await expect(page.getByText('出口已切换，已有连接继续使用原路径')).toBeVisible()
  expect((await page.request.get('/_fixture/check', { headers })).ok()).toBe(true)
  await page.getByRole('link', { name: '代理池与节点' }).click()
  await page.getByRole('combobox', { name: '代理池筛选', exact: true }).press('Enter')
  await page.getByRole('option', { name: 'web-pool', exact: true }).click()
  await page.getByRole('button', { name: '探测所选池' }).click()
  await expect(page.getByText('探测完成，故障节点仍遵循冷却时间')).toBeVisible()
  await expect(page.locator('.node-table .el-table__body tr')).toHaveCount(1)
  await expect(page.locator('.node-table')).toContainText('正常')
  // Verify listener changes use the restart confirmation and create a usable rollback snapshot.
  await page.getByRole('link', { name: '入口与认证' }).click()
  await page.getByRole('switch', { name: 'UDP 转发', exact: true }).locator('..').click()
  await page.getByRole('button', { name: '校验并应用' }).click()
  await page.getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByText('配置已应用', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: '服务运维' }).click()
  await page.getByRole('button', { name: '停止服务', exact: true }).click()
  await page.getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByRole('button', { name: '启动服务', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '启动服务', exact: true }).click()
  await expect(page.getByRole('button', { name: '停止服务', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '重启服务', exact: true }).click()
  await page.getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByText('重启完成', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '恢复上一份配置与版本' }).click()
  await page.getByRole('button', { name: '确认', exact: true }).click()
  await expect(page.getByText('回滚完成', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '读取日志' }).click()
  await expect(page.getByTestId('logs')).not.toContainText('点击“读取日志”')
  await expect(page.getByTestId('logs')).not.toContainText(token)
  await expect(page.getByTestId('logs')).not.toContainText('fixture-upstream-password')
  const c = await (await page.request.get('/api/v1/config', { headers })).json()
  expect(c.data.listener.udp).toBe(false)
  expect(c.data.activeProfile).toBe('web-pool')
  expect(
    await page.evaluate(
      () => Object.keys(localStorage).length + Object.keys(sessionStorage).length,
    ),
  ).toBe(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '打开导航' }).click()
  await page.getByRole('link', { name: '代理池与节点' }).click()
  await expect(page.getByRole('button', { name: '添加节点' })).toBeVisible()
  await page.screenshot({ animations: 'disabled', path: '../test-results/console-real-mobile.png' })
  await page.getByRole('button', { name: '打开导航' }).click()
  await page.getByRole('button', { name: '断开认证' }).click()
  await expect(page.getByRole('button', { name: '登录控制台' })).toBeVisible()
})
